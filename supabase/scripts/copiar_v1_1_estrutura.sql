-- =============================================================================
-- CÓPIA V1 -> STAGING  |  PASSO 1 de 2: ESTRUTURA
--
-- Rode na MAIN (produção). Só LÊ o catálogo do banco: não altera nada.
-- O resultado é UMA célula com um script SQL. Copie essa célula inteira e
-- rode o script na branch STAGING.
--
-- O script gerado recria no staging: tipos, sequências, funções, tabelas,
-- constraints, índices, views, RLS, policies e triggers do schema public.
-- Ele tem uma trava: se encontrar a tabela public.usuario com dados
-- (ou seja, se for rodado na produção por engano), ele para sem fazer nada.
-- =============================================================================
with
tabs as (
    select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relkind in ('r', 'p')
      and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
tipos as (
    select string_agg(
        format('create type public.%I as enum (%s);',
            t.typname,
            (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)
             from pg_enum e where e.enumtypid = t.oid)),
        E'\n' order by t.typname) as sql
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' and t.typtype = 'e'
      and not exists (select 1 from pg_depend d where d.objid = t.oid and d.deptype = 'e')
),
sequencias as (
    select string_agg(format('create sequence if not exists public.%I;', s.relname), E'\n' order by s.relname) as sql
    from pg_class s
    join pg_namespace n on n.oid = s.relnamespace
    where n.nspname = 'public' and s.relkind = 'S'
      and not exists (select 1 from pg_depend d where d.objid = s.oid and d.deptype in ('i', 'e'))
),
funcoes as (
    select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.proname) as sql
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
tabelas as (
    select string_agg(
        format(E'create table public.%I (\n%s\n);', t.relname, (
            select string_agg(
                format('    %I %s%s%s%s',
                    a.attname,
                    format_type(a.atttypid, a.atttypmod),
                    case a.attidentity
                        when 'a' then ' generated always as identity'
                        when 'd' then ' generated by default as identity'
                        else '' end,
                    case
                        when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                        when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
                        else '' end,
                    case when a.attnotnull then ' not null' else '' end),
                E',\n' order by a.attnum)
            from pg_attribute a
            left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
            where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped)),
        E'\n\n' order by t.relname) as sql
    from tabs t
),
constraints_base as (
    select string_agg(
        format('alter table public.%I add constraint %I %s;', t.relname, c.conname, pg_get_constraintdef(c.oid)),
        E'\n' order by t.relname, c.contype desc, c.conname) as sql
    from pg_constraint c
    join tabs t on t.oid = c.conrelid
    where c.contype in ('p', 'u', 'c', 'x')
),
constraints_fk as (
    select string_agg(
        format('alter table public.%I add constraint %I %s;', t.relname, c.conname, pg_get_constraintdef(c.oid)),
        E'\n' order by t.relname, c.conname) as sql
    from pg_constraint c
    join tabs t on t.oid = c.conrelid
    where c.contype = 'f'
),
indices as (
    select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by ic.relname) as sql
    from pg_index i
    join tabs t on t.oid = i.indrelid
    join pg_class ic on ic.oid = i.indexrelid
    where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)
),
views as (
    select string_agg(
        format(E'create or replace view public.%I as\n%s', v.relname, pg_get_viewdef(v.oid)),
        E'\n\n' order by v.relname) as sql
    from pg_class v
    join pg_namespace n on n.oid = v.relnamespace
    where n.nspname = 'public' and v.relkind = 'v'
      and not exists (select 1 from pg_depend d where d.objid = v.oid and d.deptype = 'e')
),
rls as (
    select string_agg(
        format('alter table public.%I enable row level security;', relname)
        || case when relforcerowsecurity then format(E'\nalter table public.%I force row level security;', relname) else '' end,
        E'\n' order by relname) as sql
    from tabs
    where relrowsecurity
),
policies as (
    select string_agg(
        format('create policy %I on public.%I as %s for %s to %s%s%s;',
            p.policyname, p.tablename, p.permissive, p.cmd,
            (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ')
             from unnest(p.roles) r),
            coalesce(E'\n    using (' || p.qual || ')', ''),
            coalesce(E'\n    with check (' || p.with_check || ')', '')),
        E'\n' order by p.tablename, p.policyname) as sql
    from pg_policies p
    where p.schemaname = 'public'
),
gatilhos as (
    select string_agg(pg_get_triggerdef(tg.oid) || ';', E'\n' order by t.relname, tg.tgname) as sql
    from pg_trigger tg
    join tabs t on t.oid = tg.tgrelid
    where not tg.tgisinternal
),
limpar as (
    select string_agg(format('drop table if exists public.%I cascade;', relname), E'\n' order by relname) as sql
    from tabs
)
select concat_ws(E'\n\n',
    '-- ===== Estrutura da V1 gerada em ' || now()::text || ' =====',
    '-- Rodar SOMENTE na branch STAGING.',
    'begin;',
    $guard$do $trava$
declare
    tem_dados boolean := false;
begin
    if to_regclass('public.usuario') is not null then
        execute 'select exists (select 1 from public.usuario)' into tem_dados;
    end if;
    if tem_dados then
        raise exception 'PARADO: public.usuario tem dados. Isto parece a PRODUÇÃO. Rode este script só na STAGING.';
    end if;
end $trava$;$guard$,
    'set local check_function_bodies = off;',
    '-- limpar cópias anteriores (só tabelas do public)',
    (select sql from limpar),
    '-- tipos',      (select sql from tipos),
    '-- sequências', (select sql from sequencias),
    '-- funções',    (select sql from funcoes),
    '-- tabelas',    (select sql from tabelas),
    '-- chaves e checks', (select sql from constraints_base),
    '-- chaves estrangeiras', (select sql from constraints_fk),
    '-- índices',    (select sql from indices),
    '-- views',      (select sql from views),
    '-- RLS',        (select sql from rls),
    '-- policies',   (select sql from policies),
    '-- triggers',   (select sql from gatilhos),
    'commit;'
) as script;
